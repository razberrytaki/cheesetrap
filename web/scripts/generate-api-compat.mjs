import { readFile, writeFile } from "node:fs/promises";
import ts from "typescript";

// A narrow bridge for this app's existing components/operations type imports.
// Orval owns every actual model and query shape. This does not recreate the
// former generator's paths, response, header, or requestBody type contracts.
const spec = JSON.parse(await readFile(new URL("../../api/openapi.json", import.meta.url), "utf8"));
const modelText = await readFile(new URL("../src/api/generated/models.ts", import.meta.url), "utf8");
// Keep the generated module canonical, including one final newline.
await writeFile(new URL("../src/api/generated/models.ts", import.meta.url), modelText.trimEnd() + "\n");
const modelAST = ts.createSourceFile("models.ts", modelText, ts.ScriptTarget.Latest, true);
const exports = new Set(modelAST.statements
  .filter((node) => ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node))
  .map((node) => node.name.text));
const model = (name) => {
  name = name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
  if (!/^[A-Za-z][A-Za-z0-9]*$/.test(name) || !exports.has(name)) {
    throw new Error(`Orval type mapping requires review: ${name}`);
  }
  return `Orval.${name}`;
};
const lines = [
  "// Generated by scripts/generate-api-compat.mjs; do not edit.",
  "// Only the app's model and operation-query contracts are provided.",
  'import type * as Orval from "./generated/models";',
  "",
  "export interface components {",
  "  schemas: {",
  ...Object.keys(spec.components.schemas).map((name) => `    ${JSON.stringify(name)}: ${model(name)};`),
  "  };",
  "}",
  "",
  "export interface operations {",
];
const ids = new Set();
for (const item of Object.values(spec.paths)) {
  if (item.parameters) throw new Error("Path-level parameters require bridge review");
  for (const method of ["get", "put", "post", "delete", "patch", "head", "options", "trace"]) {
    const operation = item[method];
    if (!operation) continue;
    const id = operation.operationId;
    if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(id) || ids.has(id)) {
      throw new Error(`Operation naming requires bridge review: ${id}`);
    }
    ids.add(id);
    const parameters = operation.parameters ?? [];
    if (parameters.some((p) => p.$ref)) throw new Error("Parameter refs require bridge review");
    const query = parameters.filter((p) => p.in === "query");
    const name = id.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join("") + "Params";
    const queryType = query.length ? model(name) : "never";
    const optional = query.some((p) => p.required) ? "" : "?";
    lines.push(`  ${JSON.stringify(id)}: { parameters: { query${optional}: ${queryType} } };`);
  }
}
lines.push("}", "");
await writeFile(new URL("../src/api/schema.d.ts", import.meta.url), lines.join("\n"));
