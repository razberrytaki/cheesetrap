"""Generate the console's shared CSS from its project token source."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = json.loads((root / 'tokens/cheesetrap.json').read_text())
lines = ['/* Generated by scripts/build-console-tokens.py; edit tokens/cheesetrap.json. */', ':root {']
for name, token in source['primitive'].items():
    lines.append(f"  --{name}: {token['$value']};")
lines.append('}')
(root / 'tokens.css').write_text('\n'.join(lines) + '\n')
